#!/bin/sh
# Writes a dev pad script (stdout) that goes from the title screen to a Kick Off match with the given Game Settings,
# for --fifa19_pad_script. Like kickoff.txt, it assumes the EA User Agreement and the club are saved in the profile.
#
#   scripts/pad/match.sh [--stadium N] [--season N] [--time N] [--weather N] [--cmd "<pad command>"]... > match.txt
#
# Each setting is a number of steps from the defaults, which the menu shows again for every match (Molton Road,
# Autumn / Fall, 3:00 PM, Clear); negative steps go left. Known steps:
#   stadium  1 O Dromo, 2 Old Trafford, 3 Olympiastadion
#   time     half an hour a step: 1 3:30 PM ... 7 6:30 PM
#   weather  1 Overcast, 2 Rainy, 3 Snowy
# --cmd lines run just before the match is started (e.g. "set metal_debug_dump_address 492380160").

stadium=0 season=0 time=0 weather=0 cmds=""
while [ $# -gt 0 ]; do
  case "$1" in
    --stadium) stadium=$2; shift 2 ;;
    --season) season=$2; shift 2 ;;
    --time) time=$2; shift 2 ;;
    --weather) weather=$2; shift 2 ;;
    --cmd) cmds="$cmds$2
"; shift 2 ;;
    *) echo "unknown option $1" >&2; exit 1 ;;
  esac
done

# Presses right (or left for a negative count) n times.
steps() {
  n=$1 button=right
  if [ "$n" -lt 0 ]; then n=$((-n)); button=left; fi
  while [ "$n" -gt 0 ]; do printf 'press %s\nwait 1s\n' $button; n=$((n - 1)); done
}

cat <<EOF
# Generated by scripts/pad/match.sh --stadium $stadium --season $season --time $time --weather $weather
wait 35s
press start
wait 25s
# Main menu: Kick Off, side select, both teams, both kits.
press a
wait 10s
press a
wait 6s
press a
wait 4s
press a
wait 14s
press a
wait 3s
press a
wait 22s
# Game Settings, then its rows: Half Length, Difficulty, Stadium, Season, Time of Day, Weather.
press right
wait 1s
press right
wait 1s
press a
wait 4s
press down
wait 1s
press down
wait 1s
EOF
steps "$stadium"
printf 'press down\nwait 1s\n'
steps "$season"
printf 'press down\nwait 1s\n'
steps "$time"
printf 'press down\nwait 1s\n'
steps "$weather"
printf '%s' "$cmds"
cat <<EOF
log match settings done
press b
wait 3s
press left
wait 1s
press left
wait 1s
# Play Match; the difficulty note (shown until a first match is finished) also starts it.
press a
wait 8s
press a
# The skill game runs while the match loads (a minute, or over two with the machine busy); Start only works once
# it says so. Start then A, every 12 seconds for three minutes: once the match is on, Start opens the pause menu
# and A picks its first item, Resume (B there leaves the match).
wait 40s
EOF
i=0
while [ $i -lt 15 ]; do printf 'press start\nwait 2s\npress a\nwait 10s\n'; i=$((i + 1)); done
cat <<EOF
# Skip the walk-out.
press a
wait 3s
press a
log match script done
EOF
